SELECT
    p.id,
    pr.id
FROM mapa m
JOIN productos p
    ON regexp_replace(UPPER(TRIM(p.nombre)), '\s+', ' ', 'g')
     = regexp_replace(UPPER(TRIM(m.producto)), '\s+', ' ', 'g')
JOIN proveedores pr
    ON regexp_replace(UPPER(TRIM(pr.nombre)), '\s+', ' ', 'g')
     = regexp_replace(UPPER(TRIM(m.proveedor)), '\s+', ' ', 'g')
ON CONFLICT (producto_id)
