    pr.id AS proveedor_id,
    pr.nombre AS proveedor,
    COUNT(*) AS productos
FROM productos_proveedores pp
JOIN proveedores pr ON pr.id = pp.proveedor_id
GROUP BY pr.id, pr.nombre
ORDER BY pr.id;